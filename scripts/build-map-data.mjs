// Precomputes the Global Network map geometry into src/data/worldMap.js.
// The dot-matrix land needs ~9,000 point-in-polygon tests; doing that once
// here means the browser ships no d3/topojson and does no geometry work.
// Re-run with `npm run map:data` after changing locations below.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { geoContains, geoEquirectangular, geoPath } from 'd3-geo';
import { feature } from 'topojson-client';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const world = JSON.parse(fs.readFileSync(path.join(root, 'scripts/data/land-110m.json'), 'utf8'));
const land = feature(world, world.objects.land);

const W = 960, H = 470;
const proj = geoEquirectangular().scale(153).translate([W / 2, H / 2 + 40]);
const r1 = n => Math.round(n * 10) / 10;
const pathGen = geoPath(proj).digits(1);

const HQ = [73.85, 18.62];
// t: self = Grandspan, est = established, jv = joint venture, up = upcoming
const LOCATIONS = [
  { n: 'London', c: [-0.12, 51.5], t: 'self' }, { n: 'Frankfurt', c: [8.68, 50.11], t: 'est' },
  { n: 'Singapore', c: [103.82, 1.35], t: 'est' }, { n: 'Perth', c: [115.86, -31.95], t: 'est' },
  { n: 'Nairobi', c: [36.82, -1.29], t: 'est' }, { n: 'Accra', c: [-0.19, 5.6], t: 'est' },
  { n: 'Guatemala City', c: [-90.51, 14.63], t: 'jv' },
  { n: 'Abu Dhabi', c: [54.37, 24.45], t: 'up' }, { n: 'Orlando', c: [-81.38, 28.54], t: 'up' },
  { n: 'Ottawa', c: [-75.7, 45.42], t: 'up' }, { n: 'Brasília', c: [-47.88, -15.79], t: 'up' },
];
const LABEL_LEFT = ['Ottawa', 'Orlando', 'Guatemala City', 'Brasília', 'Accra', 'London'];
const LABEL_DY = { Frankfurt: -6, London: -8 };

// Dot-matrix land, encoded as one path of zero-length segments drawn with
// round caps (one SVG element instead of thousands of <circle>s).
const step = 7;
let dots = '';
for (let x = 0; x < W; x += step) {
  for (let y = 0; y < H; y += step) {
    const ll = proj.invert([x, y]);
    if (ll && ll[1] > -58 && geoContains(land, ll)) dots += `M${x} ${y}h0`;
  }
}

const [hx, hy] = proj(HQ);
const data = {
  dots,
  hq: [r1(hx), r1(hy)],
  locations: LOCATIONS.map(d => {
    const [x, y] = proj(d.c);
    return {
      name: d.n,
      type: d.t,
      x: r1(x),
      y: r1(y),
      arc: pathGen({ type: 'LineString', coordinates: [HQ, d.c] }),
      labelLeft: LABEL_LEFT.includes(d.n),
      labelDy: LABEL_DY[d.n] ?? 4,
    };
  }),
};

const out = `// Generated by scripts/build-map-data.mjs. Do not edit by hand.\nexport default ${JSON.stringify(data)};\n`;
fs.writeFileSync(path.join(root, 'src/data/worldMap.js'), out);
console.log(`wrote src/data/worldMap.js (${(out.length / 1024).toFixed(1)} KB, ${dots.split('M').length - 1} dots)`);
